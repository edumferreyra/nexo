create extension if not exists pgcrypto;
create extension if not exists pg_cron;
create extension if not exists pg_net;

-- ---------------------------------------------------------------- tablas

create table if not exists public.agenda_items (
  id uuid primary key default gen_random_uuid(),
  codigo bigint generated by default as identity unique,
  tipo text not null check (tipo in ('compromiso','tarea','seguimiento','recordatorio')),
  categoria text not null check (categoria in
    ('personal','familiar','edubotika_admin','academico','comercial','marketing','proyectos')),
  titulo text not null,
  descripcion text,
  estado text not null default 'pendiente'
    check (estado in ('pendiente','en_curso','hecho','cancelado','vencido')),
  prioridad text not null default 'media' check (prioridad in ('alta','media','baja')),
  responsable text,
  origen text not null default 'telegram' check (origen in ('telegram','pc','agente')),
  empieza timestamptz,
  vence timestamptz,
  todo_el_dia boolean not null default false,
  rrule text,
  padre_id uuid references public.agenda_items(id) on delete set null,
  proyecto_id uuid,
  ledger_task_id text,
  visibilidad text not null default 'personal' check (visibilidad in ('personal','oficina')),
  creado timestamptz not null default now(),
  actualizado timestamptz not null default now(),
  completado_en timestamptz,
  cancelado_en timestamptz
);

create index if not exists agenda_empieza_idx on public.agenda_items (empieza);
create index if not exists agenda_vence_idx on public.agenda_items (vence);
create index if not exists agenda_estado_idx on public.agenda_items (estado);

create table if not exists public.reminders (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.agenda_items(id) on delete cascade,
  dispara_en timestamptz not null,
  anticipacion_min integer not null default 15,
  estado text not null default 'pendiente'
    check (estado in ('pendiente','enviando','enviado','pospuesto','cancelado','error')),
  enviado_en timestamptz,
  reclamado_en timestamptz,
  intentos integer not null default 0,
  ultimo_error text,
  clave_idempotencia text not null unique,
  creado timestamptz not null default now()
);

create index if not exists reminders_due_idx on public.reminders (estado, dispara_en);

create table if not exists public.messages (
  update_id bigint primary key,
  chat_id bigint not null,
  user_id bigint not null,
  texto text,
  procesado_en timestamptz not null default now()
);

create table if not exists public.pending_jobs (
  id uuid primary key default gen_random_uuid(),
  creado timestamptz not null default now(),
  estado text not null default 'pendiente'
    check (estado in ('pendiente','tomado','hecho','error')),
  payload jsonb not null,
  resultado jsonb,
  tomado_en timestamptz,
  notificado_en timestamptz,
  intentos integer not null default 0
);

create index if not exists pending_jobs_estado_idx on public.pending_jobs (estado, creado);

create table if not exists public.events (
  id bigserial primary key,
  item_id uuid,
  accion text not null,
  payload jsonb,
  canal text,
  ts timestamptz not null default now()
);

-- ---------------------------------------------------------------- updated_at

create or replace function public.tg_touch_updated()
returns trigger language plpgsql as $$
begin
  new.actualizado = now();
  return new;
end $$;

drop trigger if exists agenda_touch on public.agenda_items;
create trigger agenda_touch before update on public.agenda_items
  for each row execute function public.tg_touch_updated();

-- ---------------------------------------------------------------- búsquedas

create or replace function public.find_item(p_codigo bigint)
returns public.agenda_items
language sql stable as $$
  select * from public.agenda_items where codigo = p_codigo limit 1;
$$;

-- ---------------------------------------------------------------- recordatorios

-- Reclama hasta p_limit recordatorios vencidos de forma atómica.
create or replace function public.claim_due_reminders(p_limit integer default 20)
returns setof public.reminders
language plpgsql security definer set search_path = public as $$
begin
  -- Recupera los que quedaron "enviando" si la función murió a mitad de camino.
  update public.reminders
     set estado = 'pendiente', reclamado_en = null
   where estado = 'enviando' and reclamado_en < now() - interval '10 minutes';

  return query
  with due as (
    select id from public.reminders
    where estado = 'pendiente' and dispara_en <= now()
    order by dispara_en
    limit greatest(1, least(p_limit, 50))
    for update skip locked
  )
  update public.reminders r
     set estado = 'enviando', intentos = r.intentos + 1, reclamado_en = now()
    from due
   where r.id = due.id
  returning r.*;
end $$;

create or replace function public.mark_reminder_sent(p_id uuid)
returns void language sql security definer set search_path = public as $$
  update public.reminders
     set estado = 'enviado', enviado_en = now(), reclamado_en = null, ultimo_error = null
   where id = p_id;
$$;

create or replace function public.mark_reminder_failed(p_id uuid, p_error text)
returns void language sql security definer set search_path = public as $$
  update public.reminders
     set estado = case when intentos >= 5 then 'error' else 'pendiente' end,
         reclamado_en = null,
         ultimo_error = left(coalesce(p_error, 'error'), 500)
   where id = p_id;
$$;

create or replace function public.cancel_reminders_for_item(p_item uuid)
returns void language sql security definer set search_path = public as $$
  update public.reminders
     set estado = 'cancelado'
   where item_id = p_item and estado in ('pendiente','enviando');
$$;

